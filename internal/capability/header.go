import (
	"fmt"
	"strconv"
	"strings"
)

func NativeHeader(c Catalog) ([]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("/* Code generated by cmd/capgen from internal/capability/windows_coff.json; DO NOT EDIT. */\n")
	b.WriteString("#ifndef BOFBENCH_CAPABILITIES_GENERATED_H\n#define BOFBENCH_CAPABILITIES_GENERATED_H\n\n")
	fmt.Fprintf(&b, "#define BOFBENCH_CAPABILITY_SCHEMA_VERSION %d\n", c.SchemaVersion)
	fmt.Fprintf(&b, "#define BOFBENCH_CAPABILITY_CATALOG_VERSION %s\n", strconv.Quote(c.CatalogVersion))
	fmt.Fprintf(&b, "#define MACHINE_AMD64 0x%04x\n", c.Machine.Code)
	fmt.Fprintf(&b, "#define SECTION_CNT_UNINITIALIZED_DATA 0x%08x\n", c.SectionFlags.UninitializedData)
	for _, relocation := range c.SortedRelocations() {
		fmt.Fprintf(&b, "#define REL_AMD64_%s 0x%04x\n", relocation.Name, relocation.Code)
	}
	b.WriteString("\n#define BOFBENCH_BEACON_API_LIST(X) \\\n")
	for i, api := range c.BeaconAPIs {
		continuation := " \\\n"
		if i == len(c.BeaconAPIs)-1 {
			continuation = "\n"
		}
		fmt.Fprintf(&b, "    X(%s)%s", api, continuation)
	}
	b.WriteString("\nstatic const char *const bofbench_fallback_libraries[] = {\n")
	for _, library := range c.FallbackLibraries {
		fmt.Fprintf(&b, "    %s,\n", strconv.Quote(library))
	}
	b.WriteString("};\n\n")
	b.WriteString("typedef struct { const char *symbol; const char *library; } bofbench_symbol_import;\n")
	b.WriteString("static const bofbench_symbol_import bofbench_symbol_imports[] = {\n")
	for _, item := range c.SymbolImports {
		fmt.Fprintf(&b, "    {%s, %s},\n", strconv.Quote(item.Symbol), strconv.Quote(item.Library))
	}
	b.WriteString("};\n\n")
	b.WriteString("static const char *bofbench_relocation_type_name(uint16_t type) {\n    switch (type) {\n")
	for _, relocation := range c.SortedRelocations() {
		fmt.Fprintf(&b, "    case REL_AMD64_%s: return %s;\n", relocation.Name, strconv.Quote(relocation.Name))
	}
	b.WriteString("    default: return \"UNKNOWN\";\n    }\n}\n\n")
	b.WriteString("static int bofbench_relocation_is_supported(uint16_t type) {\n    switch (type) {\n")
	for _, relocation := range c.SortedRelocations() {
		if relocation.Supported {
			fmt.Fprintf(&b, "    case REL_AMD64_%s:\n", relocation.Name)
		}
	}
	b.WriteString("        return 1;\n    default:\n        return 0;\n    }\n}\n\n")
	b.WriteString("static const char *bofbench_normalize_import(const char *name) {\n")
	for _, prefix := range c.ImportPointerPrefixes {
		fmt.Fprintf(&b, "    if (strncmp(name, %s, %d) == 0) return name + %d;\n", strconv.Quote(prefix), len(prefix), len(prefix))
	}
	b.WriteString("    return name;\n}\n\n")
	b.WriteString("static const char *bofbench_symbol_import_library(const char *name) {\n")
	b.WriteString("    size_t index;\n")
	b.WriteString("    const char *normalized = bofbench_normalize_import(name);\n")
	b.WriteString("    for (index = 0; index < sizeof(bofbench_symbol_imports) / sizeof(bofbench_symbol_imports[0]); index++) {\n")
	b.WriteString("        if (strcmp(normalized, bofbench_symbol_imports[index].symbol) == 0) return bofbench_symbol_imports[index].library;\n")
	b.WriteString("    }\n")
	b.WriteString("    return NULL;\n}\n\n")
	b.WriteString("static int bofbench_is_import_pointer_symbol(const char *name) {\n")
	for _, prefix := range c.ImportPointerPrefixes {
		fmt.Fprintf(&b, "    if (strncmp(name, %s, %d) == 0) return 1;\n", strconv.Quote(prefix), len(prefix))
	}
	b.WriteString("    return 0;\n}\n\n#endif\n")
	return []byte(b.String()), nil
}
